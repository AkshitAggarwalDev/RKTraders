#!/usr/bin/env python3
"""
export_products.py — Export the MySQL product catalogue (categories + products
+ product images) for a fresh Supabase/PostgreSQL database.

Usage (from the backend repo root):
    python scripts/export_products.py

Behavior:
- Reads MySQL credentials from the environment or the local `.env` file
  (DB_URL / DB_USERNAME / DB_PASSWORD), never hardcoding them.
- Exports only: category, product, product_image.
- Does NOT migrate customers, carts, orders, payments, reviews, or enquiries.
- Preserves original integer IDs so foreign keys stay meaningful.
- Emits:
    scripts/out/categories.json
    scripts/out/products.json
    scripts/out/product_images.json
    scripts/out/import_supabase.sql   (idempotent, ordered inserts)

Image files (uploads/ dir) are handled separately; the DB only stores
filenames, see scripts/migrate_images.sh.
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "out"


def load_env(path: Path) -> dict:
    env = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                env[k.strip()] = v.strip()
    return env


def parse_db_url(url: str):
    m = re.match(r"jdbc:mysql://([^:/]+):(\d+)/([^?]+)", url)
    if not m:
        bail("DB_URL is not a jdbc:mysql:// URL; this script targets local MySQL only.")
    return m.group(1), int(m.group(2)), m.group(3)


def bail(msg):
    print(msg, file=sys.stderr)
    sys.exit(1)


def q(sql, args=()):
    import mysql.connector
    conn = mysql.connector.connect(**DB, autocommit=True)
    cur = conn.cursor(dictionary=True)
    cur.execute(sql, args)
    rows = cur.fetchall()
    cur.close()
    conn.close()
    return rows


DB = None


def main():
    global DB
    file_env = load_env(ROOT / ".env")
    def env(name, default=None):
        return os.environ.get(name) or file_env.get(name) or default

    url = env("DB_URL")
    user = env("DB_USERNAME")
    pwd = env("DB_PASSWORD")
    if not (url and user):
        bail("Set DB_URL and DB_USERNAME (and DB_PASSWORD if needed) in the environment or .env")

    host, port, database = parse_db_url(url)
    DB = dict(host=host, port=port, user=user, password=pwd or "", database=database)

    try:
        import mysql.connector  # noqa: F401
    except ImportError:
        bail("pip install mysql-connector-python first.")

    OUT.mkdir(parents=True, exist_ok=True)

    categories = q("SELECT id, name, description FROM category ORDER BY id")
    products = q(
        "SELECT id, name, description, price, stock, brand, color, status, "
        "category_id, created_at, updated_at "
        "FROM product ORDER BY id"
    )
    images = q(
        "SELECT id, image_url, primary_image, product_id "
        "FROM product_image ORDER BY id"
    )

    def clean(row, keys):
        return {k: row.get(k) for k in keys}

    (OUT / "categories.json").write_text(
        json.dumps([clean(r, ["id", "name", "description"]) for r in categories], indent=2, default=str),
        encoding="utf-8"
    )
    (OUT / "products.json").write_text(
        json.dumps([clean(r, ["id", "name", "description", "price", "stock", "brand",
                              "color", "status", "category_id", "created_at", "updated_at"])
                    for r in products], indent=2, default=str),
        encoding="utf-8"
    )
    (OUT / "product_images.json").write_text(
        json.dumps([clean(r, ["id", "image_url", "primary_image", "product_id"])
                    for r in images], indent=2, default=str),
        encoding="utf-8"
    )

    sql = [
        "-- Auto-generated by scripts/export_products.py",
        "-- Import into Supabase AFTER the backend has created the PostgreSQL schema",
        "-- (run the backend once with the postgres profile and ddl-auto=update).",
        "-- Non-destructive: inserts only; stops if any catalogued ID already exists.",
        "BEGIN;",
        "",
    ]
    sql.append("-- Categories")
    sql.append("-- Abort the whole transaction if any target ID exists (empty DB expected).")
    sql.append("DO $$")
    sql.append("BEGIN")
    sql.append("IF (SELECT COUNT(*) FROM category WHERE id IN (" + ids_list([r['id'] for r in categories]) + ")) > 0")
    sql.append("   OR (SELECT COUNT(*) FROM product WHERE id IN (" + ids_list([r['id'] for r in products]) + ")) > 0")
    sql.append("   OR (SELECT COUNT(*) FROM product_image WHERE id IN (" + ids_list([r['id'] for r in images]) + ")) > 0 THEN")
    sql.append("RAISE EXCEPTION 'Duplicate ID found: catalogue rows already exist; aborting import (no data overwritten)';")
    sql.append("END IF;")
    sql.append("END $$;")
    for r in categories:
        sql.append(
            "INSERT INTO category (id, name, description) VALUES (%s, %s, %s);"
            % (r["id"], sql_str(r["name"]), sql_str(r["description"]))
        )
    sql.append("")
    sql.append("-- Products")
    for r in products:
        sql.append(
            "INSERT INTO product (id, name, description, price, stock, brand, color, "
            "status, category_id, created_at, updated_at) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s);"
            % (r["id"], sql_str(r["name"]), sql_str(r["description"]),
               r["price"], r["stock"], sql_str(r["brand"]), sql_str(r["color"]),
               sql_str(r["status"]), r["category_id"],
               ("'%s'" % r["created_at"]) if r["created_at"] else "NULL",
               ("'%s'" % r["updated_at"]) if r["updated_at"] else "NULL")
        )
    sql.append("")
    sql.append("-- Product images")
    for r in images:
        sql.append(
            "INSERT INTO product_image (id, image_url, primary_image, product_id) "
            "VALUES (%s, %s, %s, %s);"
            % (r["id"], sql_str(r["image_url"]), bool(r["primary_image"]), r["product_id"])
        )
    sql.append("")
    sql.append("-- Reset sequences so new rows keep getting fresh IDs.")
    sql.append("SELECT setval(pg_get_serial_sequence('category','id'), (SELECT COALESCE(MAX(id),1) FROM category));")
    sql.append("SELECT setval(pg_get_serial_sequence('product','id'), (SELECT COALESCE(MAX(id),1) FROM product));")
    sql.append("SELECT setval(pg_get_serial_sequence('product_image','id'), (SELECT COALESCE(MAX(id),1) FROM product_image));")
    sql.append("COMMIT;")
    (OUT / "import_supabase.sql").write_text("\n".join(sql), encoding="utf-8")

    print(f"Exported {len(categories)} categories, {len(products)} products, "
          f"{len(images)} images -> {OUT}")


def sql_str(v):
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def ids_list(ids):
    return ", ".join(str(i) for i in ids)


if __name__ == "__main__":
    main()
